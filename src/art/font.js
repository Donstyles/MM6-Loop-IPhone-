// --- face assembly ---------------------------------------------------------

const EXTRAS = '©•→←↑↓★♦';

function buildFace(name, glyphSrc, cellW, cellH, baseline, spacing, spaceAdv) {
  const order = [];
  for (let c = 32; c <= 126; c++) order.push(String.fromCharCode(c));
  for (const c of EXTRAS) order.push(c);

  const glyphs = Object.create(null);
  const index = new Map();
  order.forEach((chr, i) => {
    index.set(chr, i);
    const src = glyphSrc[chr] || [];
    // Normalise: pad every row to cellW, clamp row count to cellH. Authoring
    // mistakes then degrade into a slightly clipped glyph instead of throwing.
    const rows = [];
    for (let y = 0; y < Math.min(src.length, cellH); y++) {
      let r = src[y] || '';
      if (r.length > cellW) r = r.slice(0, cellW);
      rows.push(r);
    }
    let maxInk = -1;
    for (const r of rows) {
      for (let x = r.length - 1; x >= 0; x--) {
        if (r[x] !== '.' && r[x] !== ' ') { if (x > maxInk) maxInk = x; break; }
      }
    }
    glyphs[chr] = {
      rows,
      adv: maxInk < 0 ? spaceAdv : maxInk + 1 + spacing,
      ink: maxInk + 1,
    };
  });

  return {
    name, cellW, cellH, baseline, spacing, spaceAdv,
    lineHeight: cellH,
    order, glyphs, index,
    cols: 16,
    rows: Math.ceil(order.length / 16),
  };
}

