// --- colour handling -------------------------------------------------------

function parseColor(css) {
  if (Array.isArray(css)) return css;
  let s = String(css).trim();
  if (s[0] === '#') {
    if (s.length === 4) s = '#' + s[1] + s[1] + s[2] + s[2] + s[3] + s[3];
    const n = parseInt(s.slice(1), 16);
    return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
  }
  const m = s.match(/(-?\d+(?:\.\d+)?)/g);
  if (m && m.length >= 3) return [+m[0], +m[1], +m[2]];
  return [255, 255, 255];
}

// The engine's text colours are reserved palette entries, not colours the world
// table has to approximate: MM6 loads them into fixed indices so the interface
// hue is identical on every machine. Snapping them through the terrain ramps
// drags StarkWhite to #DED2BE and EasternBlue to a washed #4FA8D8, so the
// entries below are passed through verbatim and everything else is snapped.
const EXACT_INK = new Set([
  TEXT_NORMAL, TEXT_HILITE, TEXT_HEADER, TEXT_GOOD, TEXT_BAD, TEXT_RED,
  TEXT_LEARN, TEXT_NPC, TEXT_DARK, TEXT_HUD, TEXT_HUD_SHADOW, TEXT_SHADOW,
].map((c) => c.toUpperCase()));

/** Palette-snap a colour so the font never emits an off-palette pixel. */
function snapColor(css) {
  if (typeof css === 'string' && EXACT_INK.has(css.toUpperCase())) return parseColor(css);
  const [r, g, b] = parseColor(css);
  return snap(r, g, b);
}

// --- glyph atlas -----------------------------------------------------------

const _atlas = new Map();

/**
 * Build the two-channel glyph atlas.
 *
 * MM6's .fnt glyphs are 1 byte per pixel with 0 = transparent, 1 = SHADOW and
 * 255 = TEXT: the drop shadow is *baked into the glyph bitmap* as a second
 * colour index and the engine tints the two channels independently. That is why
 * the shadow is perfectly consistent everywhere and never doubles up between
 * adjacent letters. We do the same - the shadow mask is computed once per face
 * and both channels are painted into a single cell - so a string is one blit
 * per glyph rather than two passes.
 *
 * Cells are (cellW+1) x (cellH+1) so the +1,+1 shadow has somewhere to live.
 */
function atlasFor(faceName, color, shadow) {
  const face = FACES[faceName] || FACES.normal;
  const key = face.name + '|' + color + '|' + (shadow || '-');
  let a = _atlas.get(key);
  if (a) return a;

  const cw = face.cellW + 1, chh = face.cellH + 1;
  const { cols, rows } = face;
  const canvas = makeCanvas(cols * cw, rows * chh);
  const g = ctx2d(canvas);
  const img = g.createImageData(canvas.width, canvas.height);
  const d = img.data;
  const main = snapColor(color);
  // '+' is the secondary tone: a darkened ink used for inner shading strokes.
  const sec = snap(main[0] * 0.55, main[1] * 0.55, main[2] * 0.55);
  const sh = shadow ? snapColor(shadow) : null;

  const put = (x, y, c) => {
    const p = (y * canvas.width + x) * 4;
    d[p] = c[0]; d[p + 1] = c[1]; d[p + 2] = c[2]; d[p + 3] = 255;
  };

  face.order.forEach((chr, i) => {
    const gl = face.glyphs[chr];
    if (!gl || gl.ink <= 0) return;
    const ox = (i % cols) * cw;
    const oy = Math.floor(i / cols) * chh;
    const isInk = (x, y) => {
      const row = gl.rows[y];
      if (!row) return false;
      const c = row[x];
      return c !== undefined && c !== '.' && c !== ' ';
    };
    // SHADOW channel first: every ink pixel offset +1,+1 that is not itself ink
    // and that lands *outside* the letterform.
    //
    // The outside test is the whole trick. A raw +1,+1 offset floods every
    // counter - the bowl of o, the eye of e, the vee of M - because those are
    // one or two pixels wide at this size, and the result is the inky blob that
    // makes "Might" read as "Night". MM6's .fnt glyphs carry the shadow as
    // authored bytes rather than as a blit, and no hand-cut bitmap face lets its
    // shadow eat its own counters. So the shadow is flood-filled in from the
    // edge of the cell and only reaches what the eye would call outside.
    if (sh) {
      const gw = cw, gh = chh;
      const open = new Uint8Array(gw * gh);   // 0 unvisited, 1 outside
      const stack = [];
      const push = (x, y) => {
        if (x < 0 || y < 0 || x >= gw || y >= gh) return;
        const k = y * gw + x;
        if (open[k] || isInk(x, y)) return;
        open[k] = 1; stack.push(k);
      };
      for (let x = 0; x < gw; x++) { push(x, 0); push(x, gh - 1); }
      for (let y = 0; y < gh; y++) { push(0, y); push(gw - 1, y); }
      while (stack.length) {
        const k = stack.pop();
        const x = k % gw, y = (k / gw) | 0;
        push(x - 1, y); push(x + 1, y); push(x, y - 1); push(x, y + 1);
      }
      for (let y = 0; y < gl.rows.length; y++) {
        const row = gl.rows[y];
        for (let x = 0; x < row.length; x++) {
          if (!isInk(x, y) || isInk(x + 1, y + 1)) continue;
          const k = (y + 1) * gw + (x + 1);
          if (y + 1 >= gh || x + 1 >= gw || !open[k]) continue;
          put(ox + x + 1, oy + y + 1, sh);
        }
      }
    }
    // TEXT channel on top.
    for (let y = 0; y < gl.rows.length; y++) {
      const row = gl.rows[y];
      for (let x = 0; x < row.length; x++) {
        const ch = row[x];
        if (ch === '.' || ch === ' ' || ch === undefined) continue;
        put(ox + x, oy + y, ch === '+' ? sec : main);
      }
    }
  });
  g.putImageData(img, 0, 0);
  _atlas.set(key, canvas);
  return canvas;
}

/**
 * The pre-rendered atlas for a (face, colour, shadow) triple. 16 columns of
 * (cellW+1) x (cellH+1) cells in the face's `order`.
 */
export function glyphCanvas(face = 'normal', color = TEXT_NORMAL, shadow = TEXT_SHADOW) {
  return atlasFor(face, color, shadow);
}

// --- measuring -------------------------------------------------------------

function faceOf(name) { return FACES[name] || FACES.normal; }

function advanceOf(face, chr, tracking) {
  const gl = face.glyphs[chr] || face.glyphs['?'];
  return gl.adv + tracking;
}

/** Width/height of a single line of text, in logical pixels. */
export function measure(text, face = 'normal', tracking = 0) {
  const f = faceOf(face);
  const s = String(text);
  let w = 0;
  for (let i = 0; i < s.length; i++) w += advanceOf(f, s[i], tracking);
  if (s.length) w -= tracking;  // no trailing gap
  return { w, h: f.cellH };
}

/** Baseline offset from the top of the line box, for aligning mixed faces. */
export function baselineOf(face = 'normal') { return faceOf(face).baseline; }

export function lineHeightOf(face = 'normal') { return faceOf(face).lineHeight; }

