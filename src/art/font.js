// ---------------------------------------------------------------------------
// Hand-authored bitmap fonts.
//
// MM6's text is a fixed set of hand-drawn bitmap glyphs with a hard 1px drop
// shadow. Nothing about that survives a call to fillText: system fonts hint and
// antialias differently on every device, so the only way to be pixel-identical
// everywhere is to carry the pixels ourselves. Every glyph below is authored as
// rows of '.' (transparent), '#' (solid) and '+' (secondary/shading tone).
//
// Rows may be shorter than the cell width - missing columns are transparent -
// and a glyph may have fewer rows than the cell, which keeps the source
// readable. Advance width is derived from the ink bounding box so the faces are
// naturally proportional, exactly like the originals.
// ---------------------------------------------------------------------------

